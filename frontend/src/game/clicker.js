export function rollEvent(clicker) {
  const current = currentChapter(clicker);
  const chapterIndex = CONSPIRACY_CHAPTERS.findIndex(c => c.id === current.id);
  const chapterNumber = chapterIndex + 1;
  const validEvents = CLICKER_EVENTS.filter(e => e.minChapter <= chapterNumber);
  if (validEvents.length === 0) return null;
  return validEvents[Math.floor(Math.random() * validEvents.length)];
}
